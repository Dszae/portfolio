-- 1. Certificates Table
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    org TEXT NOT NULL,
    img TEXT NOT NULL,
    category TEXT DEFAULT 'General',
    credential_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Gallery Images & Media Table
CREATE TABLE IF NOT EXISTS public.gallery_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    alt TEXT NOT NULL,
    img TEXT NOT NULL,
    category TEXT DEFAULT 'Campus',
    type TEXT DEFAULT 'image',
    video_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Projects Table
CREATE TABLE IF NOT EXISTS public.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    category TEXT DEFAULT 'dev',
    category_label TEXT DEFAULT 'Development',
    label TEXT DEFAULT 'Project',
    type TEXT,
    description TEXT,
    img TEXT NOT NULL,
    tech JSONB DEFAULT '[]'::jsonb,
    live_url TEXT,
    github_url TEXT,
    video_url TEXT,
    featured BOOLEAN DEFAULT false,
    status TEXT DEFAULT 'published',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Blog & Articles Table
CREATE TABLE IF NOT EXISTS public.articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    excerpt TEXT,
    content TEXT,
    cover_image TEXT,
    category TEXT DEFAULT 'General',
    tags JSONB DEFAULT '[]'::jsonb,
    read_time TEXT DEFAULT '5 min read',
    status TEXT DEFAULT 'published',
    published_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Skills Table
CREATE TABLE IF NOT EXISTS public.skills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    proficiency INTEGER DEFAULT 90,
    icon TEXT,
    order_index INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Experience & Education Table
CREATE TABLE IF NOT EXISTS public.experiences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL,
    title TEXT NOT NULL,
    organization TEXT NOT NULL,
    location TEXT,
    start_date TEXT,
    end_date TEXT,
    is_current BOOLEAN DEFAULT false,
    logo TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure logo column exists if table was already created earlier
ALTER TABLE public.experiences ADD COLUMN IF NOT EXISTS logo TEXT;

-- 7. Services & Offerings Table
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    price_range TEXT,
    features JSONB DEFAULT '[]'::jsonb,
    icon TEXT DEFAULT 'Code',
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. Testimonials Table
CREATE TABLE IF NOT EXISTS public.testimonials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_name TEXT NOT NULL,
    client_role TEXT,
    company TEXT,
    avatar TEXT,
    text TEXT NOT NULL,
    rating INTEGER DEFAULT 5,
    project_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. Contact Messages (Inbox)
CREATE TABLE IF NOT EXISTS public.contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL,
    subject TEXT,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT false,
    reply_status TEXT DEFAULT 'unreplied',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. Newsletter Subscribers Table
CREATE TABLE IF NOT EXISTS public.newsletter_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    status TEXT DEFAULT 'active',
    subscribed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 11. Site-wide Settings Key-Value Store
CREATE TABLE IF NOT EXISTS public.site_settings (
    id TEXT PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. Redirects & URL Mapping Table
CREATE TABLE IF NOT EXISTS public.redirects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_path TEXT UNIQUE NOT NULL,
    destination_url TEXT NOT NULL,
    permanent BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 13. Activity & Audit Logs
CREATE TABLE IF NOT EXISTS public.activity_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action TEXT NOT NULL,
    entity TEXT NOT NULL,
    details TEXT,
    ip_address TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 14. Real-time Visitor Events & Traffic Analytics Table
CREATE TABLE IF NOT EXISTS public.visitor_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path TEXT NOT NULL,
    referrer TEXT,
    device_type TEXT,
    browser TEXT,
    country TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

