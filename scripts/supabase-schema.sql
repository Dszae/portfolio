-- 1. Create Certificates Table
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    org TEXT NOT NULL,
    img TEXT NOT NULL,
    category TEXT DEFAULT 'General',
    credential_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Gallery Images Table
CREATE TABLE IF NOT EXISTS public.gallery_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    alt TEXT NOT NULL,
    img TEXT NOT NULL,
    category TEXT DEFAULT 'Campus',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Enable Row Level Security (RLS) & Public Read Access
ALTER TABLE public.certificates ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gallery_images ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public Read Certificates" ON public.certificates
    FOR SELECT USING (true);

CREATE POLICY "Public Read Gallery" ON public.gallery_images
    FOR SELECT USING (true);

-- 4. Create Public Storage Bucket for Images (if not already exists)
INSERT INTO storage.buckets (id, name, public) 
VALUES ('portfolio-media', 'portfolio-media', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Public Storage Read" ON storage.objects
    FOR SELECT USING (bucket_id = 'portfolio-media');

CREATE POLICY "Service Role Storage All" ON storage.objects
    FOR ALL USING (bucket_id = 'portfolio-media');

